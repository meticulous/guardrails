# frozen_string_literal: true

module Guardrails
  module FeedRamp
    # COMPONENTS.md: the manifest as a page an agent (or a person) reads
    # before writing view markup. Rendered from the manifest hash alone,
    # so it's exactly as deterministic as the manifest.
    class ComponentsMarkdown
      KIND_LABELS = { "view_component" => "ViewComponent", "phlex" => "Phlex" }.freeze

      def initialize(manifest, manifest_path:)
        @manifest = manifest
        @manifest_path = manifest_path
      end

      def render
        sections = [header]
        sections << index unless components.empty?
        sections.concat(components.map { |component| component_section(component) })
        sections << tokens_section unless tokens.empty?
        "#{sections.join("\n\n")}\n"
      end

      private

      def components
        @manifest["components"]
      end

      def tokens
        @manifest["tokens"]
      end

      def header
        <<~MD.chomp
          # Components

          <!-- Generated by `rake ui_guardrails:feed_ramp:manifest` (#{@manifest["generator"]}). Don't edit; regenerate. -->

          This app's component library and design tokens. Render one of these components instead of writing
          the same markup by hand, and use a token instead of a hardcoded colour or size whenever one exists.
          Machine-readable version: `#{@manifest_path}`.

          #{summary}
        MD
      end

      def summary
        noun = components.length == 1 ? "component" : "components"
        "#{components.length} #{noun}, #{tokens.length} #{tokens.length == 1 ? "token" : "tokens"}."
      end

      def index
        components.map { |c| "- [`#{c["name"]}`](##{anchor(c["name"])}) — #{first_line(c["description"]) || KIND_LABELS[c["kind"]]}" }
                  .join("\n")
      end

      def component_section(component)
        parts = ["## #{component["name"]}"]
        source = ["`#{component["file"]}`", component["template"] && "`#{component["template"]}`", KIND_LABELS[component["kind"]]]
        parts << source.compact.join(" · ")
        parts << component["description"] if component["description"]
        parts << params_section(component["params"]) unless component["params"].empty?
        parts << slots_section(component["slots"]) unless component["slots"].empty?
        parts << previews_section(component["previews"]) unless component["previews"].empty?
        parts << example_section(component["example"])
        parts.join("\n\n")
      end

      def params_section(params)
        lines = params.map do |param|
          text = "- `#{param_signature(param)}`"
          text += param["required"] ? " (required)" : ""
          text += " [#{param["type"]}]" if param["type"]
          text += " — #{param["description"]}" if param["description"]
          text
        end
        "**Params**\n\n#{lines.join("\n")}"
      end

      def param_signature(param)
        name = param["name"]
        case param["kind"]
        when "keyword" then param["default"] ? "#{name}: #{param["default"]}" : "#{name}:"
        when "rest" then "*#{name}"
        when "keyrest" then "**#{name}"
        when "block" then "&#{name}"
        else param["default"] ? "#{name} = #{param["default"]}" : name
        end
      end

      def slots_section(slots)
        lines = slots.map do |slot|
          text = "- `#{slot["name"]}` (#{slot["kind"]})"
          text += " → `#{slot["type"]}`" if slot["type"] && !%w[lambda polymorphic].include?(slot["type"])
          text += " — one of #{slot["types"].map { |t| "`#{t}`" }.join(", ")}" if slot["types"]&.any?
          text += " — takes #{slot["params"].map { |p| "`#{param_signature(p)}`" }.join(", ")}" if slot["params"].any?
          text
        end
        heading = slots.any? { |slot| slot["heuristic"] } ? "**Slots** (methods that take a block)" : "**Slots**"
        "#{heading}\n\n#{lines.join("\n")}"
      end

      def previews_section(previews)
        names = previews.reject { |p| p["hidden"] }.map { |p| p["label"] ? "#{p["name"]} (#{p["label"]})" : p["name"] }
        return "**Previews**: none visible" if names.empty?

        "**Previews**: #{names.join(", ")}"
      end

      def example_section(example)
        return "**Example**: no usage found in previews or views." unless example

        "**Example** (from `#{example["file"]}:#{example["line"]}`)\n\n```#{example["language"]}\n#{example["source"]}\n```"
      end

      def tokens_section
        rows = tokens.map do |token|
          where = token["line"] ? "#{token["file"]}:#{token["line"]}" : token["file"]
          "| `#{token["name"]}` | `#{token["value"].gsub("|", "\\|")}` | #{token["category"]} | #{where} |"
        end
        "## Tokens\n\n| Token | Value | Category | Defined in |\n|---|---|---|---|\n#{rows.join("\n")}"
      end

      def first_line(text)
        text&.lines&.first&.strip
      end

      # GitHub's heading anchors: lowercase, punctuation dropped.
      def anchor(name)
        name.downcase.gsub(/[^a-z0-9 _-]/, "").tr(" ", "-")
      end
    end
  end
end

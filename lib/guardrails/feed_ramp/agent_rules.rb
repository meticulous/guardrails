# frozen_string_literal: true

require "pathname"
require_relative "../../guardrails"
require_relative "config"

module Guardrails
  module FeedRamp
    # Tells coding agents the component library exists, in the files they
    # read at the start of every session: a block between two marker
    # comments in CLAUDE.md, AGENTS.md (and, opted in, GEMINI.md and
    # .github/copilot-instructions.md), and a Cursor rule file of its own.
    #
    # Only the block is ever written. Everything outside the markers is
    # left byte for byte, a file without them gets the block at the end,
    # and running it again with the same manifest changes nothing. A file
    # whose markers are duplicated or unpaired is left alone with an
    # error, since there's no telling which part is ours.
    class AgentRules
      BEGIN_MARKER = "<!-- ui_guardrails:feed_ramp:begin -->"
      END_MARKER = "<!-- ui_guardrails:feed_ramp:end -->"

      TARGETS = {
        "claude" => "CLAUDE.md",
        "agents" => "AGENTS.md",
        "cursor" => ".cursor/rules/ui-guardrails.mdc",
        "gemini" => "GEMINI.md",
        "copilot" => ".github/copilot-instructions.md"
      }.freeze
      DEFAULT_TARGETS = Config::DEFAULT_RULES_TARGETS

      # The Cursor rule is a file of its own: it's rewritten whole.
      OWNED = %w[cursor].freeze

      # Claude Code's `@AGENTS.md` import: the block is already in context
      # through AGENTS.md, so CLAUDE.md doesn't get a second copy.
      AGENTS_IMPORT = %r{(?:\A|\s)@(?:\./)?AGENTS\.md\b}

      # Project configs that can start the Feed Ramp MCP server.
      MCP_CONFIGS = %w[.mcp.json .codex/config.toml .cursor/mcp.json .gemini/settings.json].freeze

      COMPONENT_INDEX_LIMIT = 50
      TOKEN_EXAMPLES = 3

      # `status` is :created, :updated, :unchanged, :removed or :skipped
      # (with `reason`).
      Change = Struct.new(:target, :path, :status, :reason, keyword_init: true)

      # The rules for a Manifest, to the targets in its config unless
      # others are given.
      def self.for(manifest, targets: nil)
        new(root: manifest.root, manifest: manifest.to_h,
            manifest_path: manifest.path.relative_path_from(manifest.root),
            markdown_path: manifest.markdown_path.relative_path_from(manifest.root),
            targets: targets || manifest.config.rules_targets, component_paths: manifest.config.component_paths)
      end

      # `manifest` is a Manifest's `to_h`; `manifest_path` and
      # `markdown_path` are where its files are, relative to root.
      def initialize(root:, manifest:, manifest_path:, markdown_path:, targets: DEFAULT_TARGETS, component_paths: [])
        @root = Pathname(root)
        @manifest = manifest
        @manifest_path = manifest_path.to_s
        @markdown_path = markdown_path.to_s
        @targets = Array(targets).map(&:to_s).uniq
        @component_paths = component_paths
        unknown = @targets - TARGETS.keys
        raise Error, "Unknown agent rules target #{unknown.join(", ")}; expected #{TARGETS.keys.join(", ")}" if unknown.any?
      end

      # Writes the block to each target. Returns one Change per target.
      def write
        each_target { |target, path| write_target(target, path) }
      end

      # Takes the block out of each target, and deletes a file left empty
      # (or the Cursor rule).
      def remove
        each_target(skip_imports: false) { |target, path| remove_target(target, path) }
      end

      # Targets whose file doesn't hold the current block.
      def stale
        each_target(dry_run: true) { |target, path| write_target(target, path, dry_run: true) }
          .reject { |change| %i[unchanged skipped].include?(change.status) }
      end

      # The managed block, markers included, with no trailing newline.
      def block(heading: "##")
        lines = [BEGIN_MARKER,
                 "<!-- Generated by `rake ui_guardrails:feed_ramp:rules` from #{@manifest_path}. " \
                 "Edits between these markers are overwritten. -->",
                 "#{heading} UI components and design tokens", ""]
        lines.concat(instructions)
        lines.concat(["", *component_index]) if components.any?
        lines.concat(["", *token_index]) if tokens.any?
        lines << END_MARKER
        lines.join("\n")
      end

      private

      def components
        @manifest.fetch("components", [])
      end

      def tokens
        @manifest.fetch("tokens", [])
      end

      def instructions
        list = []
        if components.any?
          list << "- This app has a component library. Before writing markup in a view, partial or component, " \
                  "look in `#{@markdown_path}` for a component that already does the job and render it. " \
                  "Each one's params, slots, previews and a real usage example are there; " \
                  "`#{@manifest_path}` has the same data as JSON."
          list << "- Follow the component's usage example rather than copying its HTML. " \
                  "Only write a new component when none fits, and say why."
          if mcp_installed?
            list << "- The `ui_guardrails` MCP server answers the same questions as tools: `search_components`, " \
                    "`get_component`, and `check_snippet` to check ERB or Phlex before writing the file."
          end
        end
        if tokens.any?
          list << "- Use the design tokens listed in `#{@markdown_path}` instead of raw colours, " \
                  "pixel sizes or arbitrary Tailwind values."
        end
        list << "- `rake ui_guardrails:audit` reports UI drift (raw colours, inline styles, missing alt text) " \
                "in the views you changed."
        list
      end

      def mcp_installed?
        MCP_CONFIGS.any? { |file| (path = @root.join(file)).file? && path.read.include?("ui_guardrails-mcp") }
      end

      def component_index
        shown = components.first(COMPONENT_INDEX_LIMIT).map do |component|
          summary = first_sentence(component["description"])
          "- `#{component["name"]}`#{" — #{summary}" if summary}"
        end
        more = components.length - shown.length
        shown << "- …and #{more} more in `#{@markdown_path}`." if more.positive?
        ["Components (#{components.length}):", "", *shown]
      end

      def token_index
        by_category = tokens.group_by { |token| token["category"] }.sort_by { |category, _| category.to_s }
        lines = by_category.map do |category, list|
          names = list.first(TOKEN_EXAMPLES).map { |token| "`#{token["name"]}`" }
          names << "…" if list.length > TOKEN_EXAMPLES
          "- #{category} (#{list.length}): #{names.join(", ")}"
        end
        ["Design tokens (#{tokens.length}):", "", *lines]
      end

      def first_sentence(text)
        return nil if text.nil? || text.strip.empty?

        sentence = text.strip.split(/(?<=[.!?])\s+/).first.gsub(/\s+/, " ")
        sentence.length > 120 ? "#{sentence[0, 119].rstrip}…" : sentence
      end

      # Yields each target and its path, skipping CLAUDE.md when it
      # imports AGENTS.md (and AGENTS.md is a target), and any file that's
      # a link to one already handled.
      def each_target(skip_imports: true, dry_run: false)
        seen = {}
        @targets.map do |target|
          path = @root.join(TARGETS.fetch(target))
          real = path.exist? ? path.realpath : path
          if (other = seen[real])
            next Change.new(target: target, path: path, status: :skipped, reason: "same file as #{TARGETS[other]}")
          end

          seen[real] = target
          if skip_imports && imports_agents?(target, path)
            # A block written before the import was added goes; the one
            # in AGENTS.md is what Claude reads now.
            had_block = !markers(path.read, path).nil?
            remove_target(target, path) if had_block && !dry_run
            next Change.new(target: target, path: path, status: had_block ? :removed : :skipped,
                            reason: "imports AGENTS.md")
          end

          yield target, path
        end
      end

      def imports_agents?(target, path)
        target == "claude" && @targets.include?("agents") && path.file? && path.read.match?(AGENTS_IMPORT)
      end

      def write_target(target, path, dry_run: false)
        text = path.file? ? path.read : nil
        content = OWNED.include?(target) ? owned_content(text, path) : with_block(text, path)
        status = if text.nil? then :created
                 elsif text == content then :unchanged
                 else :updated
                 end
        if !dry_run && status != :unchanged
          path.dirname.mkpath
          path.write(content)
        end
        Change.new(target: target, path: path, status: status)
      end

      def remove_target(target, path)
        return Change.new(target: target, path: path, status: :unchanged) unless path.file?

        text = path.read
        range = markers(text, path)
        return Change.new(target: target, path: path, status: :unchanged) unless range

        eol = text.include?("\r\n") ? "\r\n" : "\n"
        before = text[0...range.begin].sub(/\s*\z/, "")
        after = text[range.end..].sub(/\A\s*\n/, "")
        rest = OWNED.include?(target) ? "" : [before, after].reject(&:empty?).join(eol * 2)
        if rest.strip.empty?
          path.delete
          path.dirname.rmdir if OWNED.include?(target) && path.dirname.empty?
        else
          path.write(after.empty? ? "#{rest}#{eol}" : rest)
        end
        Change.new(target: target, path: path, status: :removed)
      end

      # The file with the block in place of the old one, or added at the
      # end. Keeps the file's own line endings.
      def with_block(text, path)
        crlf = text&.include?("\r\n")
        block = crlf ? self.block.gsub("\n", "\r\n") : self.block
        eol = crlf ? "\r\n" : "\n"
        return "#{block}#{eol}" if text.nil? || text.strip.empty?

        range = markers(text, path)
        return "#{text[0...range.begin]}#{block}#{text[range.end..]}" if range

        "#{text.sub(/\s*\z/, "")}#{eol}#{eol}#{block}#{eol}"
      end

      # A Cursor project rule, attached when the agent works on views and
      # components. Refuses to replace a file Feed Ramp didn't write.
      def owned_content(text, path)
        if text && !text.strip.empty? && markers(text, path).nil?
          raise Error, "#{relative(path)} wasn't written by ui_guardrails; move it aside or add the rules by hand"
        end

        dirs = (["app/views"] + @component_paths).map { |dir| dir.chomp("/") }.uniq
        globs = dirs.reject { |dir| dirs.any? { |other| dir.start_with?("#{other}/") } }.map { |dir| "#{dir}/**/*" }
        <<~MDC
          ---
          description: Use this app's UI components and design tokens instead of writing markup by hand
          globs: #{globs.join(",")}
          alwaysApply: false
          ---

          #{block(heading: "#")}
        MDC
      end

      # The character range from the begin marker to the end of the end
      # marker, or nil when the text has neither.
      def markers(text, path)
        begins = text.scan(BEGIN_MARKER).length
        ends = text.scan(END_MARKER).length
        return nil if begins.zero? && ends.zero?

        start = text.index(BEGIN_MARKER)
        finish = text.index(END_MARKER)
        if begins != 1 || ends != 1 || finish < start
          found = begins == 1 && ends == 1 ? "the end marker before the begin marker" : "#{begins} begin and #{ends} end markers"
          raise Error, "#{relative(path)}: expected one ui_guardrails:feed_ramp begin marker followed by one end marker, " \
                       "found #{found}; fix them by hand"
        end

        start...(finish + END_MARKER.length)
      end

      def relative(path)
        path.relative_path_from(@root).to_s
      end
    end
  end
end
